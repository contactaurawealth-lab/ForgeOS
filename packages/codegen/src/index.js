import crypto from 'node:crypto';
import path from 'node:path';
import fs from 'node:fs/promises';
import { safeValidateAppSpecification } from '@forgeos/app-schema';

/**
 * @typedef {Object} GeneratedFile
 * @property {string} filePath - Relative file path (e.g. 'src/App.tsx')
 * @property {string} content - Source code content
 * @property {string} hash - SHA-256 hash of content
 * @property {boolean} isUserEditable - Whether this file is designated for user edits
 */

/**
 * Computes deterministic SHA-256 checksum of content
 * @param {string} content
 * @returns {string}
 */
export function computeHash(content) {
  return crypto.createHash('sha256').update(content, 'utf8').digest('hex');
}

/**
 * Generates unified line diff between two strings
 * @param {string} oldStr
 * @param {string} newStr
 * @param {string} fileName
 * @returns {string}
 */
export function computeUnifiedDiff(oldStr, newStr, fileName = 'file') {
  if (oldStr === newStr) return '';

  const oldLines = oldStr ? oldStr.split('\n') : [];
  const newLines = newStr ? newStr.split('\n') : [];
  const diff = [];

  diff.push(`--- a/${fileName}`);
  diff.push(`+++ b/${fileName}`);
  diff.push(`@@ -1,${oldLines.length} +1,${newLines.length} @@`);

  let i = 0, j = 0;
  while (i < oldLines.length || j < newLines.length) {
    if (i < oldLines.length && j < newLines.length && oldLines[i] === newLines[j]) {
      diff.push(` ${oldLines[i]}`);
      i++;
      j++;
    } else {
      if (i < oldLines.length) {
        diff.push(`-${oldLines[i]}`);
        i++;
      }
      if (j < newLines.length) {
        diff.push(`+${newLines[j]}`);
        j++;
      }
    }
  }

  return diff.join('\n');
}

/**
 * Deterministically generates source files from an AppSpecification
 * @param {any} spec
 * @returns {GeneratedFile[]}
 */
export function generateSourceFiles(spec, options = {}) {
  const validation = safeValidateAppSpecification(spec);
  if (!validation.success) {
    throw new Error(`Cannot generate code from invalid specification: ${validation.errors.map(e => e.message).join(', ')}`);
  }

  const validSpec = validation.data;
  const files = [];

  // 1. types.ts
  const typesContent = generateTypesFile(validSpec);
  files.push({
    filePath: 'src/types.ts',
    content: typesContent,
    hash: computeHash(typesContent),
    isUserEditable: false,
  });

  // 2. Component registry file
  const componentsContent = generateComponentsFile(validSpec);
  files.push({
    filePath: 'src/components/ForgeComponents.tsx',
    content: componentsContent,
    hash: computeHash(componentsContent),
    isUserEditable: false,
  });

  // 3. Main App component
  const appContent = generateAppFile(validSpec);
  files.push({
    filePath: 'src/App.tsx',
    content: appContent,
    hash: computeHash(appContent),
    isUserEditable: true,
  });

  // 4. index.html
  const htmlContent = generateIndexHtml(validSpec);
  files.push({
    filePath: 'index.html',
    content: htmlContent,
    hash: computeHash(htmlContent),
    isUserEditable: false,
  });

  // 5. package.json
  const pkgContent = generatePackageJson(validSpec);
  files.push({
    filePath: 'package.json',
    content: pkgContent,
    hash: computeHash(pkgContent),
    isUserEditable: false,
  });

  // 6. Manifest file
  const manifest = {
    forgeOsVersion: '1.0.0',
    specId: validSpec.metadata.id,
    specVersion: validSpec.schemaVersion,
    generatedAt: options.generatedAt || validSpec.metadata.updatedAt || '2026-10-18T00:00:00.000Z',
    files: files.map(f => ({ filePath: f.filePath, hash: f.hash })),
  };
  const manifestContent = JSON.stringify(manifest, null, 2) + '\n';
  files.push({
    filePath: 'forgeos-manifest.json',
    content: manifestContent,
    hash: computeHash(manifestContent),
    isUserEditable: false,
  });

  // Sort files by relative path for guaranteed deterministic ordering
  files.sort((a, b) => a.filePath.localeCompare(b.filePath));

  return files;
}

function generateTypesFile(spec) {
  return `/**
 * Generated by ForgeOS - Type Definitions
 * Specification: ${spec.metadata.name} (${spec.metadata.version})
 */

export interface AppMetadata {
  id: string;
  name: string;
  title: string;
  description: string;
  version: string;
}

export interface AppState {
${(spec.state || []).map(s => `  ${s.key}: ${getTypeScriptType(s.type)};`).join('\n')}
}

export type AppActionName = ${(spec.actions || []).map(a => `'${a.name}'`).join(' | ') || 'string'};

export interface ActionPayload {
  action: AppActionName;
  payload?: unknown;
}
`;
}

function getTypeScriptType(type) {
  switch (type) {
    case 'string': return 'string';
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return 'unknown[]';
    case 'object': return 'Record<string, unknown>';
    default: return 'any';
  }
}

